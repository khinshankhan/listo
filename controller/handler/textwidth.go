type font struct {
	size, other float64
	// widths from space to tilde
	widths [95]float64
}

func (f font) width(s string) float64 {
	w := 0.0
	for _, r := range s {
		switch {
		case r >= ' ' && r <= '~':
			w += f.widths[r-' ']
		case r >= 0x2e80:
			w += f.size
		default:
			w += f.other
		}
	}
	return w
}
